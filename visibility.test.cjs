const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const context = { module: { exports: {} }, globalThis: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, "visibility.js"), "utf8"), context);
const visibility = context.module.exports;
const now = 1000;
const state = { positioned: true, pointerOver: false, pointerActive: false, dragging: false, focused: false, menuOpen: false, touchUntil: 0 };

assert.equal(visibility.shouldShow(state, now), false);
assert.equal(visibility.isExcludedRoute("/stories/123"), true);
assert.equal(visibility.isExcludedRoute("/direct/inbox"), true);
assert.equal(visibility.isExcludedRoute("/reels/abc"), false);
assert.equal(visibility.isExcludedRoute("/p/abc"), false);
visibility.pointerMoved(state);
assert.equal(visibility.shouldShow(state, now), true);
visibility.stopPointer(state);
assert.equal(state.pointerOver, true);
assert.equal(visibility.shouldShow(state, now), false);
visibility.pointerMoved(state);
visibility.pointerLeft(state);
assert.equal(visibility.shouldShow(state, now), false);
visibility.setDragging(state, true);
assert.equal(visibility.shouldShow(state, now), true);
visibility.setDragging(state, false);
assert.equal(visibility.shouldShow(state, now), false);
visibility.setFocus(state, true);
assert.equal(visibility.shouldShow(state, now), true);
visibility.pointerMoved(state);
visibility.setFocus(state, false);
visibility.stopPointer(state);
assert.equal(visibility.shouldShow(state, now), false);
visibility.setFocus(state, false);
state.menuOpen = true;
assert.equal(visibility.shouldShow(state, now), true);
state.menuOpen = false;
assert.equal(visibility.shouldShow(state, now), false);
visibility.showTouch(state, now, 500);
assert.equal(visibility.shouldShow(state, 1499), true);
assert.equal(visibility.shouldShow(state, 1500), false);
state.positioned = false;
visibility.setDragging(state, true);
assert.equal(visibility.shouldShow(state, now), false);

console.log("Auto-hide behavior checks passed.");
